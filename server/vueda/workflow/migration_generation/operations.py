class WorkflowChangeTypes(enum.Enum):
    ADDED = "added"
    CHANGED = "changed"
    DELETED = "deleted"


# The action kind a generated workflow migration opens, and the kind the legacy conversion gives a
# row a migration wrote. Reading it back separates a migration's writes from a person's edit.
MIGRATION_ACTION_KIND = "migration"


# The comment right after Django's "Generated by" comment that marks a generated workflow migration. Reading the
# marked migrations tells which recorded changes a migration already holds.
MIGRATION_MODIFIED_COMMENT = (
    f"# Modified using VUEDA makevuedamigrations command (workflow changes).  "
    f"Please do not delete this comment.{NEWLINE}"
)

# The marker that makeworkflowmigrations wrote, before makevuedamigrations replaced it. A migration that carries
# it is still a generated workflow migration.
LEGACY_MIGRATION_MODIFIED_COMMENT = (
    f"# Modified using VUEDA makeworkflowmigrations command.  Please do not delete this comment.{NEWLINE}"
)

# Every marker that identifies a generated workflow migration.
MIGRATION_MODIFIED_COMMENTS = (MIGRATION_MODIFIED_COMMENT, LEGACY_MIGRATION_MODIFIED_COMMENT)


