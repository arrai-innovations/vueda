"""Helpers for migration generation: which apps a run covers, and the migrations that those apps already have."""

__all__ = (
    "INSTALLED_PACKAGE_DIRECTORIES",
    "MARKER_SEARCH_LINES",
    "GeneratedMigration",
    "app_migration_names",
    "generated_migrations",
    "is_generated_migration",
    "is_installed_package_app",
    "is_vueda_app",
    "latest_migration_names",
    "project_app_labels",
    "user_app_label",
)

import dataclasses
import importlib
import importlib.util
from pathlib import Path

from django.apps import apps as django_apps
from django.conf import settings
from django.core.management import CommandError
from django.db.migrations.loader import MigrationLoader

from vueda.user.management.commands.utils import get_migrations_path


# A marker comment sits right after Django's "Generated by" comment, so it is always near the top of the file.
MARKER_SEARCH_LINES = 20


@dataclasses.dataclass(frozen=True)
class GeneratedMigration:
    """A migration that VUEDA generated, and the ``changed_data`` list that it holds."""

    name: str
    path: Path
    changed_data: tuple


def app_migration_names(app_label):
    """Return the names of the migrations of ``app_label`` in the order that ``migrate`` applies them.

    The migration files are read again on every call.
    """
    importlib.invalidate_caches()
    graph = MigrationLoader(None, ignore_no_migrations=True).graph
    names = []
    for leaf in sorted(graph.leaf_nodes(app_label)):
        for node_app_label, name in graph.forwards_plan(leaf):
            if node_app_label == app_label and name not in names:
                names.append(name)

    return tuple(names)


def is_generated_migration(migration_path, marker_comments):
    """Return whether the file at ``migration_path`` carries one of ``marker_comments`` near its top."""
    markers = tuple(marker.strip() for marker in marker_comments)
    with open(migration_path, encoding="utf-8") as migration_file:
        for line_number, line in enumerate(migration_file):
            if line_number > MARKER_SEARCH_LINES:
                break
            # strip() and startswith() ignore the line ending, so a file written on another OS still matches.
            if line.startswith(markers):
                return True

    return False


def generated_migrations(app_label, marker_comments):
    """Return the migrations of ``app_label`` that carry one of ``marker_comments``, in the order applied.

    Each one is loaded from its file, so the ``changed_data`` is current even after the file was rewritten in
    this process. The result is empty when the app has no migrations directory.
    """
    migrations_path = get_migrations_path(django_apps.get_app_config(app_label))
    if migrations_path is None:
        return ()

    found = []
    for name in app_migration_names(app_label):
        migration_path = Path(migrations_path) / f"{name}.py"
        if not migration_path.exists() or not is_generated_migration(migration_path, marker_comments):
            continue

        spec = importlib.util.spec_from_file_location("migration", migration_path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        found.append(GeneratedMigration(name=name, path=migration_path, changed_data=tuple(module.changed_data)))

    return tuple(found)


# The directory names that Python installs third-party packages into.
INSTALLED_PACKAGE_DIRECTORIES = frozenset(("site-packages", "dist-packages"))


def is_installed_package_app(app_label):
    """Return whether the app ``app_label`` is installed as a package, under ``site-packages`` or ``dist-packages``.

    A project cannot commit a migration written into such an app, and a reinstall puts the package's own files
    back.
    """
    return bool(INSTALLED_PACKAGE_DIRECTORIES & set(Path(django_apps.get_app_config(app_label).path).parts))


def is_vueda_app(app_label):
    """Return whether the app ``app_label`` belongs to the ``vueda`` package, so VUEDA ships its migrations.

    In a project, VUEDA is installed as a package, so only a run in VUEDA's own repository writes into such an app.
    """
    name = django_apps.get_app_config(app_label).name
    return name == "vueda" or name.startswith("vueda.")


def project_app_labels():
    """Return the labels of the installed apps that belong to the project, in installed order.

    An app installed under ``site-packages``, or ``dist-packages`` on Debian's system Python, is a third-party
    package, so it is left out.
    """
    return tuple(
        app_config.label
        for app_config in django_apps.get_app_configs()
        if not is_installed_package_app(app_config.label)
    )


def user_app_label():
    """Return the label of the app of ``AUTH_USER_MODEL``, which holds every group migration."""
    return django_apps.get_model(settings.AUTH_USER_MODEL)._meta.app_label


def latest_migration_names(app_labels):
    """Return a mapping of each app in ``app_labels`` to the name of its latest migration, read from disk now.

    An app without migrations is left out. The migration files are read again on every call, so a migration
    written since the last call is found.

    Raises ``CommandError`` for an app with more than one latest migration. Django's ``makemigrations --merge``
    joins them.
    """
    # A file written since Python last looked at its directory is otherwise missed.
    importlib.invalidate_caches()
    loader = MigrationLoader(None, ignore_no_migrations=True)
    wanted = frozenset(app_labels)
    latest = {}
    for app_label, migration_name in loader.graph.leaf_nodes():
        if app_label not in wanted:
            continue
        if app_label in latest:
            raise CommandError(
                f"The app {app_label!r} has more than one latest migration, and a new migration would depend on "
                "it. Run 'makemigrations --merge' first."
            )
        latest[app_label] = migration_name

    return latest
